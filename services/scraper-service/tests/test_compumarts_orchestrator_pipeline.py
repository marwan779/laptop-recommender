"""Unit test verifying ScrapeOrchestrator integration with the generic 8-layer pipeline for CompuMarts."""

from unittest.mock import MagicMock, patch
import pytest

from app.schemas.laptop import RetailerProduct
from app.schemas.orchestrator import ScrapeRequest
from app.services.orchestrator import ScrapeOrchestrator


def test_compumarts_orchestrator_level2_runs_generic_pipeline(tmp_path):
    """Verify ScrapeOrchestrator runs the 8-layer hardware pipeline for CompuMarts on Level 2."""
    orchestrator = ScrapeOrchestrator(
        email_service=MagicMock(),
        no_audit=True,
        ai_type="none",
        upload_to_bucket=False,
    )

    sample_product = RetailerProduct(
        store_name="Compumarts",
        store_key="compumarts",
        store_domain="compumarts.com",
        title="Lenovo Legion Pro 5 16IRX9 Gaming Laptop - Intel Core i7-14650HX 16-Cores, 16GB RAM DDR5, 1TB SSD NVMe, NVIDIA GeForce RTX 4060 8GB GDDR6, 16 inch WQXGA IPS 165Hz 300nits, Windows 11 Home",
        product_url="https://compumarts.com/products/lenovo-legion-pro-5-16irx9",
        price_egp=75000.0,
        in_stock=True,
        specs={
            "Processor": "14th Gen Intel® Core™ i7-14650HX 16 Cores, 24 Threads",
            "Memory": "16 GB DDR5-5600 SO-DIMM",
            "Storage": "1TB SSD M.2 2280 PCIe NVMe",
            "Graphics": "NVIDIA GeForce RTX 4060 8GB GDDR6",
            "Display": "16 inch WQXGA (2560x1600) IPS 165Hz 300nits Anti-glare",
            "Operating System": "Windows 11 Home",
        },
    )

    out_dir = tmp_path / "compumarts_out"
    req = ScrapeRequest(
        target_type="store",
        targets=["compumarts"],
        level=2,
        output_dir=str(out_dir),
        upload_to_bucket=False,
        send_email=False,
    )

    with patch("app.services.orchestrator.get_store_scraper") as mock_get_store:
        mock_scraper = MagicMock()
        mock_scraper.store_name = "Compumarts"
        mock_scraper.store_key = "compumarts"
        mock_scraper.base_domain = "compumarts.com"
        mock_scraper.scrape_catalog.return_value = [sample_product]
        mock_scraper.skipped_laptops = []
        mock_get_store.return_value = mock_scraper

        res = orchestrator.execute(req)

        assert res.total_targets == 1
        assert res.total_items_scraped == 1
        target_res = res.results[0]
        assert target_res.error is None
        assert target_res.store_result is not None
        assert len(target_res.store_result.products) == 1

        # Check structured_products generated by the generic 8-layer pipeline
        structured = target_res.store_result.structured_products
        assert len(structured) == 1
        item = structured[0]
        assert item["url"] == sample_product.product_url
        assert item["price_egp"] == 75000.0
        assert item["cpu_key"] == "intel_core_i7_14650hx"
        assert item["is_audited"] is False
        assert item["audit_status"] == "skipped"

        specs = item["specs"]
        assert specs["cpu"]["model"] == "Core i7-14650HX"
        assert specs["cpu"]["cores"] == 16
        assert specs["cpu"]["threads"] == 24
        assert specs["gpu"]["model"] == "GeForce RTX 4060"
        assert specs["gpu"]["vram_gb"] == 8
        assert specs["memory"]["capacity_gb"] == 16
        assert specs["memory"]["memory_type"] == "DDR5"
        assert specs["storage"]["capacity_gb"] == 1024
        assert specs["display"]["size_inches"] == 16.0
        assert specs["display"]["refresh_rate_hz"] == 165


def test_compumarts_orchestrator_level1_bypasses_deep_pipeline():
    """Verify ScrapeOrchestrator on Level 1 does not execute deep pipeline extraction."""
    orchestrator = ScrapeOrchestrator(
        email_service=MagicMock(),
        no_audit=True,
        ai_type="none",
        upload_to_bucket=False,
    )

    sample_product = RetailerProduct(
        store_name="Compumarts",
        store_key="compumarts",
        store_domain="compumarts.com",
        title="Lenovo Legion Pro 5",
        product_url="https://compumarts.com/products/lenovo-legion-pro-5",
        price_egp=75000.0,
    )

    req = ScrapeRequest(
        target_type="store",
        targets=["compumarts"],
        level=1,
        upload_to_bucket=False,
        send_email=False,
    )

    with patch("app.services.orchestrator.get_store_scraper") as mock_get_store:
        mock_scraper = MagicMock()
        mock_scraper.store_name = "Compumarts"
        mock_scraper.store_key = "compumarts"
        mock_scraper.base_domain = "compumarts.com"
        mock_scraper.scrape_catalog.return_value = [sample_product]
        mock_scraper.skipped_laptops = []
        mock_get_store.return_value = mock_scraper

        res = orchestrator.execute(req)

        assert res.total_targets == 1
        target_res = res.results[0]
        assert target_res.error is None
        assert len(target_res.store_result.products) == 1
        # Level 1 does not run the deep 8-layer hardware pipeline
        assert target_res.store_result.structured_products == []


def test_orchestrator_rejects_deactivated_stores():
    """Verify requesting non-compumarts stores records an informative error."""
    orchestrator = ScrapeOrchestrator(email_service=MagicMock())
    req = ScrapeRequest(target_type="store", targets=["sigma"], level=1)
    res = orchestrator.execute(req)
    assert len(res.results) == 1
    assert "Only 'compumarts' via the 8-layer hardware pipeline is currently active" in res.results[0].error
